"""
Headless Browser Automated Session Harvester for YouTube Ingestion.
Extracts fresh anti-bot visitor session tokens & cookies and formats them into
Netscape format at storage/harvester_cookies.txt.
Supports headless Playwright with high-fidelity HTTP fallback.
"""

import time
import logging
from pathlib import Path
from datetime import datetime
from typing import Optional, Dict, Any, List
import httpx

from shorts_engine.config.settings import settings

logger = logging.getLogger(__name__)

USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36"
)


class SessionHarvester:
    """Automated YouTube visitor session harvester."""

    @classmethod
    def get_output_path(cls, custom_path: Optional[Path] = None) -> Path:
        """Resolves target harvester cookies file path (encrypted .enc at rest)."""
        p = (
            custom_path
            or getattr(settings, "YOUTUBE_HARVESTER_COOKIES_PATH", None)
            or (settings.STORAGE_DIR / "harvester_cookies.txt.enc")
        )
        p = Path(p)
        if not p.name.endswith(".enc"):
            p = p.with_name(p.name + ".enc")
        p.parent.mkdir(parents=True, exist_ok=True)
        return p

    @classmethod
    def format_netscape_cookies(cls, cookies: List[Dict[str, Any]]) -> str:
        """
        Formats a list of cookie dictionaries into Netscape HTTP Cookie format.
        Spec: domain, flag, path, secure, expiration, name, value (tab-delimited).
        """
        lines = [
            "# Netscape HTTP Cookie File",
            "# https://curl.se/docs/http-cookies.html",
            f"# Generated by Shorts Engine Session Harvester at {datetime.utcnow().isoformat()}Z",
            "",
        ]
        now = int(time.time())
        default_expiry = now + 86400 * 30  # 30 days default

        for c in cookies:
            name = c.get("name")
            value = c.get("value")
            if not name or value is None:
                continue

            raw_domain = c.get("domain") or ".youtube.com"
            if not raw_domain.startswith(".") and not raw_domain.startswith("www."):
                raw_domain = f".{raw_domain}"
            include_subdomains = "TRUE" if raw_domain.startswith(".") else "FALSE"
            path = c.get("path") or "/"
            secure = "TRUE" if c.get("secure", True) else "FALSE"
            
            raw_exp = c.get("expires") or c.get("expiry")
            try:
                expires = int(raw_exp) if raw_exp is not None and int(raw_exp) > 0 else default_expiry
            except (ValueError, TypeError):
                expires = default_expiry

            line = f"{raw_domain}\t{include_subdomains}\t{path}\t{secure}\t{expires}\t{name}\t{value}"
            lines.append(line)

        return "\n".join(lines) + "\n"

    @classmethod
    def _harvest_playwright(cls, timeout_sec: float = 25.0) -> Optional[List[Dict[str, Any]]]:
        """Attempts headless Playwright browser cookie harvesting."""
        try:
            from playwright.sync_api import sync_playwright
            with sync_playwright() as p:
                browser = p.chromium.launch(
                    headless=True,
                    args=[
                        "--disable-blink-features=AutomationControlled",
                        "--no-sandbox",
                        "--disable-setuid-sandbox",
                        "--disable-infobars",
                        "--window-size=1280,720",
                    ],
                )
                context = browser.new_context(
                    user_agent=USER_AGENT,
                    viewport={"width": 1280, "height": 720},
                    locale="en-US",
                )
                page = context.new_page()
                page.goto("https://www.youtube.com", timeout=int(timeout_sec * 1000), wait_until="domcontentloaded")
                
                # Check for consent dialog and dismiss if present
                try:
                    consent_btn = page.query_selector('button[aria-label*="Accept"], button[aria-label*="agree"]')
                    if consent_btn:
                        consent_btn.click(timeout=3000)
                        time.sleep(1.0)
                except Exception:
                    pass

                cookies = context.cookies(["https://www.youtube.com", "https://youtube.com"])
                browser.close()
                if cookies:
                    logger.info("Playwright harvester successfully collected %d cookies.", len(cookies))
                    return cookies
        except ImportError:
            logger.debug("Playwright not installed; using HTTP session harvester fallback.")
        except Exception as e:
            logger.warning("Playwright session harvest failed (%s); trying HTTP fallback.", e)
        return None

    @classmethod
    def _harvest_http(cls, timeout_sec: float = 15.0) -> List[Dict[str, Any]]:
        """Fallback HTTP session harvester querying YouTube's visitor endpoints."""
        headers = {
            "User-Agent": USER_AGENT,
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8",
            "Accept-Language": "en-US,en;q=0.9",
            "Sec-Ch-Ua": '"Chromium";v="128", "Not;A=Brand";v="24", "Google Chrome";v="128"',
            "Sec-Ch-Ua-Mobile": "?0",
            "Sec-Ch-Ua-Platform": '"Windows"',
            "Sec-Fetch-Dest": "document",
            "Sec-Fetch-Mode": "navigate",
            "Sec-Fetch-Site": "none",
            "Sec-Fetch-User": "?1",
        }

        collected_cookies: List[Dict[str, Any]] = []
        now = int(time.time())

        with httpx.Client(headers=headers, follow_redirects=True, timeout=timeout_sec) as client:
            resp = client.get("https://www.youtube.com")
            for k, v in resp.cookies.items():
                collected_cookies.append({
                    "name": k,
                    "value": v,
                    "domain": ".youtube.com",
                    "path": "/",
                    "secure": True,
                    "expires": now + 86400 * 30,
                })

            # Ensure minimal required visitor tracking markers
            has_socs = any(c["name"] == "SOCS" for c in collected_cookies)
            if not has_socs:
                collected_cookies.append({
                    "name": "SOCS",
                    "value": "CAESEwgDEgk2NDM4MTg4NTkaAmVuIAEaBgiA_LyaBg",
                    "domain": ".youtube.com",
                    "path": "/",
                    "secure": True,
                    "expires": now + 86400 * 180,
                })

            has_pref = any(c["name"] == "PREF" for c in collected_cookies)
            if not has_pref:
                collected_cookies.append({
                    "name": "PREF",
                    "value": "f6=40000000&tz=UTC&hl=en",
                    "domain": ".youtube.com",
                    "path": "/",
                    "secure": True,
                    "expires": now + 86400 * 180,
                })

        logger.info("HTTP session harvester collected %d cookies.", len(collected_cookies))
        return collected_cookies

    @classmethod
    def run_harvest_job(
        cls,
        output_path: Optional[Path] = None,
        timeout_sec: float = 25.0,
    ) -> Dict[str, Any]:
        """
        Executes a fresh harvesting cycle and persists Netscape formatted cookies to disk.
        """
        target_path = cls.get_output_path(output_path)
        start_time = time.time()

        cookies = cls._harvest_playwright(timeout_sec=timeout_sec)
        engine_used = "playwright"
        if not cookies:
            cookies = cls._harvest_http(timeout_sec=timeout_sec)
            engine_used = "httpx"

        netscape_text = cls.format_netscape_cookies(cookies)
        from shorts_engine.security.secretbox import encrypt as secretbox_encrypt
        encrypted_text = secretbox_encrypt(netscape_text)
        with open(target_path, "w", encoding="utf-8") as f:
            f.write(encrypted_text)

        # Eliminate plaintext re-leak artifact if present
        plaintext_legacy = target_path.parent / target_path.stem
        if plaintext_legacy.exists() and plaintext_legacy.is_file():
            try:
                plaintext_legacy.unlink()
            except Exception:
                pass
        default_leak = settings.STORAGE_DIR / "harvester_cookies.txt"
        if default_leak.exists() and default_leak.is_file():
            try:
                default_leak.unlink()
            except Exception:
                pass

        elapsed = round(time.time() - start_time, 2)
        logger.info("Session harvest completed in %.2fs via %s: %s (%d cookies, encrypted)", elapsed, engine_used, target_path, len(cookies))

        return {
            "success": True,
            "engine": engine_used,
            "cookies_count": len(cookies),
            "output_path": str(target_path),
            "elapsed_sec": elapsed,
            "timestamp": datetime.utcnow().isoformat(),
        }

    @classmethod
    def get_status(cls, output_path: Optional[Path] = None) -> Dict[str, Any]:
        """Checks the existence, freshness, and size of the harvested cookies file."""
        target_path = cls.get_output_path(output_path)
        if not target_path.exists() or target_path.stat().st_size == 0:
            return {
                "exists": False,
                "fresh": False,
                "path": str(target_path),
                "message": "No harvested cookies found on disk.",
            }

        stat = target_path.stat()
        age_sec = time.time() - stat.st_mtime
        age_min = round(age_sec / 60.0, 1)

        # Count valid cookie lines by decrypting if needed
        cookie_count = 0
        try:
            from shorts_engine.security.secretbox import decrypt as secretbox_decrypt
            with open(target_path, "r", encoding="utf-8") as f:
                content = f.read()
            if target_path.name.endswith(".enc"):
                try:
                    content = secretbox_decrypt(content)
                except Exception as dec_err:
                    logger.debug("Harvester cookie decryption attempt: %s", dec_err)
            for line in content.splitlines():
                clean = line.strip()
                if clean and not clean.startswith("#"):
                    cookie_count += 1
        except Exception:
            pass

        is_fresh = age_sec < 86400 * 7  # Fresh within 7 days
        return {
            "exists": True,
            "fresh": is_fresh,
            "path": str(target_path),
            "size_bytes": stat.st_size,
            "age_minutes": age_min,
            "cookies_count": cookie_count,
            "last_modified": datetime.utcfromtimestamp(stat.st_mtime).isoformat(),
            "status": "VALID" if is_fresh and cookie_count > 0 else "STALE",
        }

    @classmethod
    def get_decrypted_cookie_text(cls, output_path: Optional[Path] = None) -> Optional[str]:
        """Returns the decrypted Netscape cookies plaintext, or None if unavailable."""
        target_path = cls.get_output_path(output_path)
        if not target_path.exists() or target_path.stat().st_size == 0:
            return None
        from shorts_engine.security.secretbox import decrypt as secretbox_decrypt
        try:
            raw = target_path.read_text(encoding="utf-8")
            if target_path.name.endswith(".enc"):
                return secretbox_decrypt(raw)
            return raw
        except Exception as e:
            logger.warning("Failed to decrypt harvester cookies from %s: %s", target_path, e)
            return None

    @classmethod
    def is_harvester_fresh(cls, max_age_hours: float = 48.0, output_path: Optional[Path] = None) -> bool:
        """Returns True if harvested cookies file exists, is non-empty, and younger than max_age_hours."""
        target_path = cls.get_output_path(output_path)
        if not target_path.exists() or target_path.stat().st_size == 0:
            return False
        age_sec = time.time() - target_path.stat().st_mtime
        return age_sec < max_age_hours * 3600.0


# Convenience aliases
run_harvest_job = SessionHarvester.run_harvest_job
get_harvester_status = SessionHarvester.get_status
is_harvester_fresh = SessionHarvester.is_harvester_fresh
